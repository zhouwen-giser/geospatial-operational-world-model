const COMMIT_SHA = /^[0-9a-f]{40}$/u;
const POSITIVE_GITHUB_NUMBER = /^[1-9][0-9]{0,31}$/u;

// Confirmed from the repository's origin remote. Keep this immutable rather
// than trusting workflow-controlled environment values to name their own
// authority boundary.
export const CANONICAL_GITHUB_REPOSITORY = "zhouwen-giser/geospatial-operational-world-model";
export const CANONICAL_GITHUB_WORKFLOW_REF =
  `${CANONICAL_GITHUB_REPOSITORY}/.github/workflows/gowm-v071-exact-head-qualification.yml@refs/heads/main`;

/**
 * Exact-head closure and the WSGS consumer baseline are publication evidence,
 * not local developer reports. Keep their authority fail-closed at the common
 * entry point so a feature branch or local shell cannot emit a Ready marker
 * carrying the IMMUTABLE_CI_ARTIFACT authority label.
 */
export function assertPostMergeMainCi(environment = process.env) {
  const sha = environment.GITHUB_SHA?.trim().toLowerCase() ?? "";
  const githubRunId = environment.GITHUB_RUN_ID?.trim() ?? "";
  const githubRunAttempt = environment.GITHUB_RUN_ATTEMPT?.trim() ?? "";
  if (
    environment.GITHUB_ACTIONS !== "true"
    || environment.GITHUB_REF !== "refs/heads/main"
    || environment.GITHUB_REF_NAME !== "main"
    || environment.GITHUB_REPOSITORY !== CANONICAL_GITHUB_REPOSITORY
    || environment.GITHUB_WORKFLOW_REF !== CANONICAL_GITHUB_WORKFLOW_REF
    || !POSITIVE_GITHUB_NUMBER.test(githubRunId)
    || !POSITIVE_GITHUB_NUMBER.test(githubRunAttempt)
    || !COMMIT_SHA.test(sha)
  ) {
    throw new Error(
      "GOWM v0.7.1 authoritative evidence may only be generated by the canonical GitHub Actions workflow on refs/heads/main with exact repository, workflow, run and GITHUB_SHA identity"
    );
  }
  return {
    commit: sha,
    ciSource: {
      githubRepository: CANONICAL_GITHUB_REPOSITORY,
      githubWorkflowRef: CANONICAL_GITHUB_WORKFLOW_REF,
      githubRunId,
      githubRunAttempt
    }
  };
}
